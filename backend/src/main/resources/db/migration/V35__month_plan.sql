-- Plano do mês (proposta de André Graccia, ADR 0021): como a pessoa divide a renda mensal confirmada em fatias.
-- Uma linha por usuário em month_plan; as fatias (até 12, com rótulo próprio) em month_plan_slice, na ordem da tela.
-- Um rascunho pode somar diferente de 100% (fica "incompleto"); só um plano que soma 100% pode ficar ativo, regra da
-- aplicação porque a soma cruza linhas. Ativo, só as fatias marcadas como compromisso entram na projeção, no dia da
-- renda principal. Tabelas novas, sem linhas antigas: os booleanos nascem NOT NULL DEFAULT FALSE.
CREATE TABLE month_plan
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT                   NOT NULL,
    active       BOOLEAN                  NOT NULL DEFAULT FALSE,
    activated_at TIMESTAMP WITH TIME ZONE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_month_plan PRIMARY KEY (id),
    CONSTRAINT fk_month_plan_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT uk_month_plan_user UNIQUE (user_id)
);

CREATE TABLE month_plan_slice
(
    month_plan_id BIGINT        NOT NULL,
    position      SMALLINT      NOT NULL,
    kind          VARCHAR(20)   NOT NULL,
    label         VARCHAR(40)   NOT NULL,
    percent       NUMERIC(5, 2) NOT NULL,
    commitment    BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_month_plan_slice PRIMARY KEY (month_plan_id, position),
    CONSTRAINT fk_month_plan_slice_plan FOREIGN KEY (month_plan_id) REFERENCES month_plan (id) ON DELETE CASCADE,
    CONSTRAINT month_plan_slice_position_check CHECK (position BETWEEN 0 AND 11),
    CONSTRAINT month_plan_slice_kind_check CHECK (kind IN
        ('FIXED', 'LEISURE', 'INVESTMENT', 'FUTURE', 'DEVELOPMENT', 'EMERGENCY', 'CUSTOM')),
    CONSTRAINT month_plan_slice_percent_check CHECK (percent BETWEEN 0 AND 100),
    -- Fixo é termômetro e Lazer é teto: medidos, nunca compromisso.
    CONSTRAINT month_plan_slice_commitment_check CHECK (NOT (commitment AND kind IN ('FIXED', 'LEISURE')))
);

COMMENT ON TABLE month_plan IS
    'Plano do mes: divisao da renda confirmada em fatias. Ativo, as fatias marcadas como compromisso entram na projecao.';
COMMENT ON TABLE month_plan_slice IS 'Fatias do plano do mes, na ordem da tela (position 0 a 11).';
