-- Patrimônio informativo (ADR 0026): investimentos que a pessoa digita. Nunca entram no saldo disponível nem na
-- projeção. Texto livre (instituição, nome, anotação) cifrado pela aplicação (ADR 0014), por isso TEXT sem limite
-- no banco: o tamanho é validado na borda. O valor atual é o registro de data mais recente em investment_value.
CREATE TABLE investment
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT                   NOT NULL,
    institution     TEXT                     NOT NULL,
    name            TEXT                     NOT NULL,
    asset_class     VARCHAR(20)              NOT NULL,
    invested_amount NUMERIC(14, 2),
    maturity_date   DATE,
    note            TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_investment PRIMARY KEY (id),
    CONSTRAINT fk_investment_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT investment_class_check CHECK (asset_class IN
        ('SAVINGS', 'FIXED_INCOME', 'FUND', 'STOCK', 'PENSION', 'CRYPTO', 'REAL_ESTATE', 'OTHER')),
    CONSTRAINT investment_invested_check CHECK (invested_amount >= 0)
);

CREATE INDEX idx_investment_user ON investment (user_id);

CREATE TABLE investment_value
(
    investment_id BIGINT         NOT NULL,
    value_date    DATE           NOT NULL,
    amount        NUMERIC(14, 2) NOT NULL,
    CONSTRAINT pk_investment_value PRIMARY KEY (investment_id, value_date),
    CONSTRAINT fk_investment_value_investment FOREIGN KEY (investment_id) REFERENCES investment (id) ON DELETE CASCADE,
    CONSTRAINT investment_value_amount_check CHECK (amount >= 0)
);

COMMENT ON TABLE investment IS
    'Investimentos informados pela pessoa. So aparecem no patrimonio; nunca no saldo disponivel nem na projecao.';

-- Minha evolução (ADR 0026): objetivos de vida, onde a pessoa está e onde quer chegar. Texto livre cifrado. Sem
-- pontuação. A ligação com uma meta é opcional e some se a meta for excluída.
CREATE TABLE life_goal
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT                   NOT NULL,
    title             TEXT                     NOT NULL,
    current_situation TEXT                     NOT NULL,
    desired_situation TEXT                     NOT NULL,
    target_date       DATE,
    estimated_cost    NUMERIC(14, 2),
    goal_id           BIGINT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_life_goal PRIMARY KEY (id),
    CONSTRAINT fk_life_goal_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT fk_life_goal_goal FOREIGN KEY (goal_id) REFERENCES goal (id) ON DELETE SET NULL,
    CONSTRAINT life_goal_cost_check CHECK (estimated_cost >= 0)
);

CREATE INDEX idx_life_goal_user ON life_goal (user_id);
CREATE INDEX idx_life_goal_goal ON life_goal (goal_id);

CREATE TABLE life_goal_step
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    life_goal_id BIGINT   NOT NULL,
    position     INTEGER  NOT NULL,
    description  TEXT     NOT NULL,
    done         BOOLEAN  NOT NULL DEFAULT FALSE,
    done_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_life_goal_step PRIMARY KEY (id),
    CONSTRAINT fk_life_goal_step_goal FOREIGN KEY (life_goal_id) REFERENCES life_goal (id) ON DELETE CASCADE
);

CREATE INDEX idx_life_goal_step_goal ON life_goal_step (life_goal_id);
