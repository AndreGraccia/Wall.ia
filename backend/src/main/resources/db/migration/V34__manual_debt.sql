-- B14 (ADR 0020): debts the person types because Open Finance does not send them. First kind: "Pix no crédito"
-- (Pix paid with the credit card limit, CET near 8% a month). The sandbox has no such product, so the balance,
-- the instalment and the monthly CET are what the person reads in their bank app. Enters only the payoff
-- planner (ADR 0013), never the daily projection: its instalments usually land on the card bill, which the
-- projection already counts.
CREATE TABLE manual_debt
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT                   NOT NULL,
    kind                VARCHAR(20)              NOT NULL,
    label               VARCHAR(60)              NOT NULL,
    outstanding_balance NUMERIC(12, 2)           NOT NULL,
    installment_amount  NUMERIC(12, 2)           NOT NULL,
    monthly_cet         NUMERIC(6, 4)            NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_manual_debt PRIMARY KEY (id),
    CONSTRAINT fk_manual_debt_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT manual_debt_kind_check CHECK (kind IN ('PIX_CREDIT')),
    CONSTRAINT manual_debt_amounts_check CHECK (outstanding_balance > 0 AND outstanding_balance <= 1000000
        AND installment_amount > 0 AND installment_amount <= 1000000),
    CONSTRAINT manual_debt_cet_check CHECK (monthly_cet > 0 AND monthly_cet <= 30)
);

CREATE INDEX idx_manual_debt_user ON manual_debt (user_id);

COMMENT ON TABLE manual_debt IS
    'Dividas informadas pelo usuario (Pix no credito). Origem MANUAL, certeza ESTIMATED; so entram no planejador de quitacao.';
COMMENT ON COLUMN manual_debt.monthly_cet IS 'CET em % ao mes, como o usuario informou (8.0 = 8% a.m.).';
