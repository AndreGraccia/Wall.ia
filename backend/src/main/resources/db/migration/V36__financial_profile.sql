-- Perfil contextual mínimo e "Meu método" (ADR 0021). Só o que a pessoa declara fica gravado; o que vem dos dados
-- (renda fixa ou variável, peso das contas fixas, número de dívidas) é calculado na hora e nunca guardado aqui.
CREATE TABLE financial_profile
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT                   NOT NULL,
    preference VARCHAR(20)              NOT NULL DEFAULT 'NOT_SAID',
    main_goal  VARCHAR(20)              NOT NULL DEFAULT 'NOT_SAID',
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_financial_profile PRIMARY KEY (id),
    CONSTRAINT fk_financial_profile_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT uk_financial_profile_user UNIQUE (user_id),
    CONSTRAINT financial_profile_preference_check CHECK (preference IN ('SIMPLE', 'DETAILED', 'NOT_SAID')),
    CONSTRAINT financial_profile_goal_check CHECK (main_goal IN
        ('STABILITY', 'LEAVE_DEBT', 'ORGANIZE_MONTH', 'BUILD_RESERVE', 'OTHER', 'NOT_SAID'))
);

-- Histórico das escolhas de método, só de acréscimo: a escolha atual é a mais recente. catalog_version diz contra qual
-- versão do catálogo (MethodCatalog.VERSION) a escolha foi feita.
CREATE TABLE method_choice
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT                   NOT NULL,
    method          VARCHAR(30)              NOT NULL,
    catalog_version VARCHAR(20)              NOT NULL,
    chosen_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_method_choice PRIMARY KEY (id),
    CONSTRAINT fk_method_choice_user FOREIGN KEY (user_id) REFERENCES public."user" (id),
    CONSTRAINT method_choice_method_check CHECK (method IN ('PERCENT_503020', 'PERCENT_ANDRE', 'ZERO_BASED',
        'PAY_YOURSELF_FIRST', 'PRIORITIES', 'INCOME_CYCLE', 'ENVELOPES', 'DEBT_AVALANCHE', 'DEBT_SNOWBALL'))
);

CREATE INDEX idx_method_choice_user ON method_choice (user_id, chosen_at DESC, id DESC);

COMMENT ON TABLE financial_profile IS 'Preferencia e objetivo declarados pela pessoa. Revisaveis; nada derivado dos dados.';
COMMENT ON TABLE method_choice IS 'Historico das escolhas de metodo de orcamento, so de acrescimo.';
